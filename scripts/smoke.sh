#!/usr/bin/env bash
#
# End-to-end smoke test for a running personal-site instance.
#
#   ./scripts/smoke.sh [base-url] [admin-user] [admin-password]
#
# Exits non-zero if any check fails.

set -uo pipefail

BASE="${1:-http://localhost:3000}"
ADMIN_USER="${2:-admin}"
ADMIN_PASS="${3:-admin12345}"

PASS=0
FAIL=0
COOKIES="$(mktemp)"
TMP="$(mktemp -d)"
trap 'rm -rf "$COOKIES" "$TMP"' EXIT

green() { printf '\033[32m%s\033[0m\n' "$1"; }
red()   { printf '\033[31m%s\033[0m\n' "$1"; }

check() {
  local label="$1" expected="$2" actual="$3"
  if [ "$expected" = "$actual" ]; then
    PASS=$((PASS + 1))
    green "  ok    $label ($actual)"
  else
    FAIL=$((FAIL + 1))
    red   "  FAIL  $label — expected $expected, got $actual"
  fi
}

contains() {
  local label="$1" needle="$2" body="$3"
  if printf '%s' "$body" | grep -q "$needle"; then
    PASS=$((PASS + 1))
    green "  ok    $label"
  else
    FAIL=$((FAIL + 1))
    red   "  FAIL  $label — '$needle' not found"
  fi
}

status() {
  curl -s -o /dev/null -w '%{http_code}' "$@"
}

echo "==> Public pages"
for path in / /about /projects /blog /experience /skills /services /testimonials \
            /awards /speaking /publications /gallery /contact /resume /search \
            /feed.xml /sitemap.xml /robots.txt /manifest.webmanifest \
            /.well-known/security.txt; do
  check "$path" 200 "$(status "$BASE$path")"
done

echo "==> Unknown paths"
check "/definitely-not-here" 404 "$(status "$BASE/definitely-not-here")"

echo "==> Assets"
for asset in /assets/css/main.css /assets/css/admin.css /assets/js/main.js \
             /assets/img/profile.svg /assets/img/favicon.svg; do
  check "$asset" 200 "$(status "$BASE$asset")"
done

echo "==> Admin authentication"
check "login page" 200 "$(status "$BASE/admin/login")"
check "guest is redirected" 303 "$(status "$BASE/admin")"

LOGIN_STATUS="$(curl -s -c "$COOKIES" -o /dev/null -w '%{http_code}' \
  -X POST "$BASE/admin/login" \
  --data-urlencode "username=$ADMIN_USER" \
  --data-urlencode "password=$ADMIN_PASS")"
check "login accepted" 303 "$LOGIN_STATUS"

echo "==> Admin pages"
for path in /admin /admin/posts /admin/posts/new /admin/pages /admin/pages/new \
            /admin/projects /admin/projects/new /admin/taxonomy /admin/comments \
            /admin/messages /admin/subscribers /admin/media /admin/users \
            /admin/users/new /admin/settings /admin/logs /admin/redirects \
            /admin/newsletter /admin/profile /admin/backup; do
  check "$path" 200 "$(status -b "$COOKIES" "$BASE$path")"
done

echo "==> CSRF protection"
CSRF="$(curl -s -b "$COOKIES" "$BASE/admin/posts/new" \
  | grep -o 'name="csrf_token" value="[^"]*"' | head -1 \
  | sed 's/.*value="//; s/"//')"
check "csrf token issued" 1 "$(printf '%s' "$CSRF" | grep -c .)"

NO_CSRF="$(status -b "$COOKIES" -X POST "$BASE/admin/posts/new" \
  --data-urlencode "title=Should not be created" \
  --data-urlencode "content=body")"
check "mutation without csrf is rejected" 403 "$NO_CSRF"

WITH_CSRF="$(status -b "$COOKIES" -X POST "$BASE/admin/posts/new" \
  --data-urlencode "title=Smoke test post" \
  --data-urlencode "slug=smoke-test-post" \
  --data-urlencode "excerpt=Created by the smoke test." \
  --data-urlencode "content=## Hello" \
  --data-urlencode "status=draft" \
  --data-urlencode "csrf_token=$CSRF")"
check "mutation with csrf is accepted" 303 "$WITH_CSRF"

echo "==> Contact form"
CONTACT="$(status -X POST "$BASE/contact" \
  --data-urlencode "name=Smoke Test" \
  --data-urlencode "email=smoke@example.com" \
  --data-urlencode "subject=Hello" \
  --data-urlencode "message=This message was generated by the smoke test.")"
check "contact form accepted" 303 "$CONTACT"

INVALID="$(curl -s -X POST "$BASE/contact" \
  --data-urlencode "name=A" \
  --data-urlencode "email=not-an-email" \
  --data-urlencode "message=hi")"
contains "contact form validates" "valid e-mail address" "$INVALID"

echo "==> Newsletter"
check "subscribe accepted" 200 "$(status -X POST "$BASE/newsletter/subscribe" \
  --data-urlencode "email=smoke-reader@example.com")"

echo
echo "-----------------------------------------"
printf 'passed: %d   failed: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
green "All smoke tests passed."
